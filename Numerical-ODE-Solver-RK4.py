import numpy as np
def uex(t):
  z= np.sin(t**2)+np.cos(t**2)
  return z
def os(t,u,v):
  z=v
  q=(1/t)*v-4*t**2*u
  return z,q
def rk(f,t,u,v,h):
  ku,kv=f(t,u,v)
  kv1=[u]
  kuu,kvv=f(t+h/2,
            u+h/2*ku,
            v+h/2*kv)
  ku3,kv3=f(t+h/2,
            u+h/2*kuu,
            v+h/2*kvv)
  ku4,kv4=f(t+h,
            u+h*ku3,
            v+h*kv3)
  un=u+h/6*(ku+2*kuu+2*ku3+ku4)
  vn=v+h/6*(kv+2*kvv+2*kv3+kv4)
  kv1.append(vn)
  return un,vn
t0=1.0
u0=np.sin(t0**2)+np.cos(t0**2)
v0=2*t0*(np.cos(t0**2)-np.sin(t0**2))
h=0.01
te=20.0
tv=np.arange(t0,te+h,h)
uv=np.zeros_like(tv)
s=len(tv)
vv=np.zeros_like(tv)
y0=np.array([u0,v0])
uv[0]=u0
vv[0]=v0
utt=uex(20)
print(f"exact={utt}")
ss=s-1
for i in range(1,len(tv)):
  uv[i],vv[i]=rk(os,tv[i-1],
                 uv[i-1],vv[i-1],h)
ue=np.sin(tv**2)+np.cos(tv**2)
er=np.abs(uv[i]-ue[-1])
import matplotlib.pyplot as plt
plt.figure(figsize=(10,6))
plt.plot(tv,uv,label='rk4',linewidth=2)
plt.plot(tv,ue,label='exact',linestyle='--',linewidth=2)
plt.xlabel('t')
plt.ylabel('ut)')
plt.legend()
plt.grid(True)
plt.show()
print(f"error t={te}:   {er}")
print(f"n:{ss-1}")